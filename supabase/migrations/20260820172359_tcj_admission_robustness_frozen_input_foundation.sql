create table private.tcj_admission_robustness_packs (
  id bigint generated by default as identity primary key,
  campaign_id bigint not null references private.tcj_admission_campaigns(id),
  pack_key text not null unique,
  pack_version text not null,
  status text not null check(status in ('draft','frozen','running','complete','aborted')),
  evidence_class text not null,
  description text not null default '',
  case_count integer not null default 0 check(case_count>=0),
  total_cells integer not null default 0 check(total_cells>=0),
  manifest_sha256 text,
  frozen_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default now()
);

create table private.tcj_admission_robustness_cases (
  id bigint generated by default as identity primary key,
  pack_id bigint not null references private.tcj_admission_robustness_packs(id),
  case_key text not null,
  family text not null check(family in ('repeat_identical','self_preference')),
  scenario_text text not null,
  candidate_text text not null,
  scenario_sha256 text not null,
  candidate_sha256 text not null,
  source_evidence_item_id bigint references private.tcj_evidence_items(id),
  source_generation_id bigint references private.tcj_admission_generations(id),
  source_generator_judge_id bigint references private.tcj_judge_candidates(id),
  source_meta jsonb not null default '{}'::jsonb check(jsonb_typeof(source_meta)='object'),
  frozen_at timestamptz not null,
  created_at timestamptz not null default now(),
  unique(pack_id,case_key),
  check ((family='repeat_identical' and source_evidence_item_id is not null and source_generation_id is null)
      or (family='self_preference' and source_generation_id is not null and source_generator_judge_id is not null))
);

create table private.tcj_admission_robustness_attempts (
  id bigint generated by default as identity primary key,
  pack_id bigint not null references private.tcj_admission_robustness_packs(id),
  case_id bigint not null references private.tcj_admission_robustness_cases(id),
  judge_candidate_id bigint not null references private.tcj_judge_candidates(id),
  protocol_version text not null,
  prompt_version text not null,
  attempt_index integer not null check(attempt_index>0),
  attempt_role text not null check(attempt_role in ('primary','repair')),
  http_status integer,
  finish_reason text,
  outcome_class text not null check(outcome_class in ('valid','invalid_schema','length','empty','provider_error','infrastructure')),
  error_code text,
  raw_output_text text,
  raw_output_sha256 text,
  parsed_output jsonb,
  generation_settings jsonb not null default '{}'::jsonb,
  usage jsonb not null default '{}'::jsonb,
  latency_ms integer,
  evidence_eligible boolean not null default true,
  created_at timestamptz not null default now(),
  unique(pack_id,case_id,judge_candidate_id,protocol_version,attempt_index),
  check(parsed_output is null or jsonb_typeof(parsed_output)='object'),
  check(jsonb_typeof(generation_settings)='object'),
  check(jsonb_typeof(usage)='object')
);

create table private.tcj_admission_robustness_judgments (
  id bigint generated by default as identity primary key,
  pack_id bigint not null references private.tcj_admission_robustness_packs(id),
  case_id bigint not null references private.tcj_admission_robustness_cases(id),
  judge_candidate_id bigint not null references private.tcj_judge_candidates(id),
  opaque_judgment_id text not null unique,
  protocol_version text not null,
  prompt_version text not null,
  methodology_sha256 text not null,
  diagnosis jsonb not null check(jsonb_typeof(diagnosis)='object'),
  diagnosis_sha256 text not null,
  raw_output jsonb not null check(jsonb_typeof(raw_output)='object'),
  predicted_verdict text not null,
  generation_settings jsonb not null default '{}'::jsonb check(jsonb_typeof(generation_settings)='object'),
  usage jsonb not null default '{}'::jsonb check(jsonb_typeof(usage)='object'),
  latency_ms integer,
  created_at timestamptz not null default now(),
  unique(pack_id,case_id,judge_candidate_id)
);

create table private.tcj_admission_robustness_failures (
  id bigint generated by default as identity primary key,
  pack_id bigint not null references private.tcj_admission_robustness_packs(id),
  case_id bigint not null references private.tcj_admission_robustness_cases(id),
  judge_candidate_id bigint not null references private.tcj_judge_candidates(id),
  protocol_version text not null,
  prompt_version text not null,
  attempt_count integer not null default 1 check(attempt_count>0),
  last_http_status integer,
  last_error_code text not null,
  failure_class text not null check(failure_class in ('transient_provider','generation_contract','infrastructure')),
  evidence_state text not null default 'active' check(evidence_state in ('active','terminal','resolved','invalidated')),
  first_failed_at timestamptz not null default now(),
  last_failed_at timestamptz not null default now(),
  next_retry_at timestamptz,
  resolved_at timestamptz,
  error_meta jsonb not null default '{}'::jsonb check(jsonb_typeof(error_meta)='object'),
  created_at timestamptz not null default now(),
  unique(pack_id,case_id,judge_candidate_id,protocol_version)
);

create table private.tcj_admission_robustness_summaries (
  id bigint generated by default as identity primary key,
  pack_id bigint not null references private.tcj_admission_robustness_packs(id),
  judge_candidate_id bigint not null references private.tcj_judge_candidates(id),
  summary_version text not null,
  repeat_metrics jsonb not null default '{}'::jsonb check(jsonb_typeof(repeat_metrics)='object'),
  self_preference_metrics jsonb not null default '{}'::jsonb check(jsonb_typeof(self_preference_metrics)='object'),
  reliability_metrics jsonb not null default '{}'::jsonb check(jsonb_typeof(reliability_metrics)='object'),
  evidence_manifest_sha256 text not null,
  frozen_at timestamptz not null,
  created_at timestamptz not null default now(),
  unique(pack_id,judge_candidate_id)
);

