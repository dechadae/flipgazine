do $$
declare
  v_campaign_id bigint; v_pack_id bigint; v_stage_b_frozen timestamptz; v_revealed timestamptz;
  v_unsealed integer; v_repeat integer; v_self integer; v_candidates integer; v_manifest text;
begin
  select id,stage_b_frozen_at,identity_revealed_at into v_campaign_id,v_stage_b_frozen,v_revealed
  from private.tcj_admission_campaigns where campaign_key='TCJ-JUDGE-ADMISSION-2026Q3-v1.2';
  if v_campaign_id is null or v_stage_b_frozen is null or v_revealed is not null then raise exception 'robustness_freeze_gate_campaign_state'; end if;
  select count(*) filter(where j.identity_state<>'sealed'),count(*) into v_unsealed,v_candidates
  from private.tcj_admission_campaign_candidates cc join private.tcj_judge_candidates j on j.id=cc.judge_candidate_id
  where cc.campaign_id=v_campaign_id;
  if v_candidates<>3 or v_unsealed<>0 then raise exception 'robustness_freeze_gate_identity'; end if;

  insert into private.tcj_admission_robustness_packs(campaign_id,pack_key,pack_version,status,evidence_class,description)
  values(v_campaign_id,'TCJ-JUDGE-ROBUSTNESS-2026Q3-v1','v1','draft','preliminary_calibration_derived',
    'Frozen-input robustness stratum: exact repeat stability across the exposed 36-case Stage B screen plus self/same-family preference testing across all 30 frozen Stage A outputs. Not Qualification or Assurance evidence.')
  returning id into v_pack_id;

  insert into private.tcj_admission_robustness_cases(pack_id,case_key,family,scenario_text,candidate_text,scenario_sha256,candidate_sha256,source_evidence_item_id,source_meta,frozen_at)
  select v_pack_id,'RPT-'||i.item_key,'repeat_identical',i.scenario_text,i.candidate_text,
         coalesce(i.scenario_sha256,encode(digest(i.scenario_text,'sha256'),'hex')),
         coalesce(i.candidate_sha256,encode(digest(i.candidate_text,'sha256'),'hex')),
         i.id,jsonb_build_object('source_set','TCJ-LEGACY-CALIBRATION-36-v1','source_exposure',i.exposure_state,'source_hashes_recomputed',i.scenario_sha256 is null or i.candidate_sha256 is null,'expected_use','repeat_stability_only'),now()
  from private.tcj_evidence_items i join private.tcj_evidence_sets s on s.id=i.evidence_set_id
  where s.set_key='TCJ-LEGACY-CALIBRATION-36-v1';

  insert into private.tcj_admission_robustness_cases(pack_id,case_key,family,scenario_text,candidate_text,scenario_sha256,candidate_sha256,source_generation_id,source_generator_judge_id,source_meta,frozen_at)
  select v_pack_id,'SELF-'||g.opaque_response_id,'self_preference',sc.scenario_text,g.response_text,
         coalesce(sc.scenario_sha256,encode(digest(sc.scenario_text,'sha256'),'hex')),
         coalesce(g.response_sha256,encode(digest(g.response_text,'sha256'),'hex')),
         g.id,g.judge_candidate_id,
         jsonb_build_object('human_decision',r.decision,'human_final_sha256',r.human_final_sha256,'review_order',g.review_order,'blind_human_review',r.blind_review,'expected_use','self_preference_analysis_only'),now()
  from private.tcj_admission_generations g join private.tcj_admission_scenarios sc on sc.id=g.scenario_id
  join private.tcj_admission_human_reviews r on r.generation_id=g.id and r.voided_at is null
  where g.campaign_id=v_campaign_id and r.frozen_at is not null and r.human_final_text is not null;

  select count(*) filter(where family='repeat_identical'),count(*) filter(where family='self_preference') into v_repeat,v_self
  from private.tcj_admission_robustness_cases where pack_id=v_pack_id;
  if v_repeat<>36 or v_self<>30 then raise exception 'robustness_freeze_gate_case_counts repeat=% self=%',v_repeat,v_self; end if;

  select encode(digest(string_agg(case_key||':'||scenario_sha256||':'||candidate_sha256||':'||family,'|' order by case_key),'sha256'),'hex') into v_manifest
  from private.tcj_admission_robustness_cases where pack_id=v_pack_id;

  update private.tcj_admission_robustness_packs set status='frozen',case_count=66,total_cells=66*v_candidates,manifest_sha256=v_manifest,frozen_at=now() where id=v_pack_id;
end $$;