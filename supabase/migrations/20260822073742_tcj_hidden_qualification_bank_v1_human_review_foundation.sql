create or replace function private.tcj_prevent_frozen_qualification_protocol_mutation()
returns trigger
language plpgsql
security definer
set search_path=pg_catalog,private
as $$
begin
  if old.threshold_frozen_at is not null and (
       new.threshold_spec is distinct from old.threshold_spec
    or new.threshold_sha256 is distinct from old.threshold_sha256
    or new.threshold_frozen_at is distinct from old.threshold_frozen_at
  ) then
    raise exception 'qualification_thresholds_immutable';
  end if;
  if old.status in ('bank_frozen','running','complete','retired','compromised') and (
       new.evidence_set_id is distinct from old.evidence_set_id
    or new.profile_id is distinct from old.profile_id
    or new.protocol_version is distinct from old.protocol_version
    or new.item_target is distinct from old.item_target
    or new.candidate_target is distinct from old.candidate_target
    or new.human_manifest_sha256 is distinct from old.human_manifest_sha256
    or new.bank_frozen_at is distinct from old.bank_frozen_at
  ) then
    raise exception 'frozen_qualification_protocol_immutable';
  end if;
  return new;
end;
$$;
