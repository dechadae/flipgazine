create or replace function private.tcj_qualification_ratings_valid(v jsonb)
returns boolean
language sql
immutable
set search_path=pg_catalog
as $$
  select jsonb_typeof(v)='object'
    and (select count(*) from jsonb_object_keys(v))=6
    and v ?& array['intent','thai_pragmatics','bff_voice','lexical_social_fit','stance','composition']
    and (v->>'intent') ~ '^[1-4]$'
    and (v->>'thai_pragmatics') ~ '^[1-4]$'
    and (v->>'bff_voice') ~ '^[1-4]$'
    and (v->>'lexical_social_fit') ~ '^[1-4]$'
    and (v->>'stance') ~ '^[1-4]$'
    and (v->>'composition') ~ '^[1-4]$';
$$;
revoke all on function private.tcj_qualification_ratings_valid(jsonb) from public,anon,authenticated;

