  id bigint generated by default as identity primary key,
  protocol_key text not null unique,
  evidence_set_id bigint not null unique references private.tcj_evidence_sets(id),
  profile_id text not null,
  protocol_version text not null,
  status text not null default 'draft_review' check (status in ('draft_review','bank_frozen','running','complete','retired','compromised')),
  item_target integer not null check (item_target>0),
  candidate_target integer not null check (candidate_target>0),
  threshold_spec jsonb not null,
  threshold_sha256 text not null check (length(threshold_sha256)=64),
  threshold_frozen_at timestamptz not null,
  human_manifest_sha256 text,
