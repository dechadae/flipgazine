create or replace function private.tcj_qualification_review_hash(
  p_scenario text,p_candidate text,p_ratings jsonb,p_severity text,p_flags text[],p_confidence text,p_ambiguous boolean,p_note text
) returns text
language sql
immutable
set search_path=pg_catalog,extensions
as $$
  select encode(extensions.digest(jsonb_build_object(
    'scenario',p_scenario,
    'candidate',p_candidate,
    'ratings',p_ratings,
    'severity',p_severity,
    'flags',to_jsonb(coalesce(p_flags,'{}'::text[])),
    'confidence',p_confidence,
    'human_ambiguous',p_ambiguous,
    'note',coalesce(p_note,'')
  )::text,'sha256'),'hex');
$$;
revoke all on function private.tcj_qualification_review_hash(text,text,jsonb,text,text[],text,boolean,text) from public,anon,authenticated;

create or replace function private.tcj_prevent_frozen_qualification_review_mutation()
returns trigger
language plpgsql
security definer
set search_path=pg_catalog,private
as $$
begin
  if old.review_state='frozen' or old.frozen_at is not null then
    raise exception 'frozen_qualification_review_immutable';
  end if;
  return case when tg_op='DELETE' then old else new end;
end;
$$;
revoke all on function private.tcj_prevent_frozen_qualification_review_mutation() from public,anon,authenticated;
