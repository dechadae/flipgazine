create or replace function private.tcj_prevent_frozen_dossier_mutation()
returns trigger
language plpgsql
security definer
set search_path=pg_catalog,private,extensions
as $$
begin
  if old.frozen_at is not null then
    raise exception 'frozen_passport_dossier_immutable';
  end if;
  return case when tg_op='DELETE' then old else new end;
end;
$$;
revoke all on function private.tcj_prevent_frozen_dossier_mutation() from public, anon, authenticated;

drop trigger if exists tcj_passport_dossier_immutable_trg on private.tcj_admission_passport_dossiers;
create trigger tcj_passport_dossier_immutable_trg
before update or delete on private.tcj_admission_passport_dossiers
for each row execute function private.tcj_prevent_frozen_dossier_mutation();

