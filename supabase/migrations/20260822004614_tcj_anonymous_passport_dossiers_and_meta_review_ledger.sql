create table if not exists private.tcj_admission_passport_dossiers (
  id bigint generated by default as identity primary key,
  campaign_id bigint not null references private.tcj_admission_campaigns(id),
  judge_candidate_id bigint not null references private.tcj_judge_candidates(id),
  opaque_dossier_id text not null unique,
  dossier_version text not null,
  profile_id text not null,
  admission_protocol_version text not null,
  evidence_class text not null,
  dossier jsonb not null,
  dossier_sha256 text not null,
  stage_a_manifest_sha256 text not null,
  stage_b_manifest_sha256 text not null,
  robustness_manifest_sha256 text not null,
  perturbation_manifest_sha256 text not null,
  frozen_at timestamptz not null default pg_catalog.now(),
  created_at timestamptz not null default pg_catalog.now(),
  unique(campaign_id,judge_candidate_id,dossier_version),
  check (jsonb_typeof(dossier)='object'),
  check (length(dossier_sha256)=64),
  check (length(stage_a_manifest_sha256)=64),
  check (length(stage_b_manifest_sha256)=64),
  check (length(robustness_manifest_sha256)=64),
  check (length(perturbation_manifest_sha256)=64)
);

create table if not exists private.tcj_admission_meta_reviews (
  id bigint generated by default as identity primary key,
  campaign_id bigint not null references private.tcj_admission_campaigns(id),
  dossier_id bigint not null references private.tcj_admission_passport_dossiers(id),
  reviewer_slot text not null check (reviewer_slot in ('chatgpt','grok')),
  review_protocol_version text not null,
  dossier_sha256 text not null,
  reviewer_provider text,
  reviewer_model text,
  review_state text not null default 'pending' check (review_state in ('pending','valid','contract_failure','infrastructure_failure','invalidated')),
  raw_output_text text,
  raw_output_sha256 text,
  parsed_review jsonb,
  parsed_review_sha256 text,
  failure_code text,
  failure_meta jsonb not null default '{}'::jsonb,
  frozen_at timestamptz,
  created_at timestamptz not null default pg_catalog.now(),
  unique(dossier_id,reviewer_slot,review_protocol_version),
  check (jsonb_typeof(failure_meta)='object'),
  check (parsed_review is null or jsonb_typeof(parsed_review)='object'),
  check (raw_output_sha256 is null or length(raw_output_sha256)=64),
  check (parsed_review_sha256 is null or length(parsed_review_sha256)=64),
  check (length(dossier_sha256)=64)
);

